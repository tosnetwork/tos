#!/usr/bin/env bash
#
# testnet-ctl.sh - Manage local TOS testnet services
#
# Usage:
#   ./scripts/testnet-ctl.sh install   # install systemd units
#   ./scripts/testnet-ctl.sh start     # start all services
#   ./scripts/testnet-ctl.sh stop      # stop all services
#   ./scripts/testnet-ctl.sh restart   # restart all services
#   ./scripts/testnet-ctl.sh status    # show service status
#   ./scripts/testnet-ctl.sh logs [N]  # tail logs for validator N (default: all)
#   ./scripts/testnet-ctl.sh uninstall # stop and remove systemd units

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SERVICES="tos-dht tos-validator@1 tos-validator@2 tos-validator@3 tos-validator@4"
UNIT_DIR="/etc/systemd/system"

install_services() {
    echo "Installing systemd unit files..."
    # Services are generated by setup-testnet.sh directly into /etc/systemd/system/
    sudo systemctl daemon-reload
    sudo systemctl enable tos-dht tos-validator@1 tos-validator@2 tos-validator@3 tos-validator@4 2>/dev/null || true
    echo "Services installed and enabled."
}

start_services() {
    echo "Starting TOS testnet..."
    sudo systemctl start tos-dht
    sleep 2  # give DHT time to bind
    sudo systemctl start tos-validator@1 tos-validator@2 tos-validator@3 tos-validator@4
    echo "All services started."
    sleep 1
    show_status
}

stop_services() {
    echo "Stopping TOS testnet..."
    # Stop any leftover @5 too (a higher-numbered legacy unit) so a 4-node
    # reinstall doesn't leave a zombie validator behind.
    sudo systemctl stop tos-validator@5 2>/dev/null || true
    sudo systemctl stop tos-validator@4 tos-validator@3 tos-validator@2 tos-validator@1 tos-dht 2>/dev/null || true
    echo "All services stopped."
}

restart_services() {
    stop_services
    sleep 1
    start_services
}

show_status() {
    for svc in $SERVICES; do
        status=$(sudo systemctl is-active "$svc" 2>/dev/null || echo "inactive")
        printf "  %-24s %s\n" "$svc" "$status"
    done
}

show_logs() {
    local node="${1:-}"
    if [ -n "$node" ]; then
        # Validate input: must be a single digit 1-4
        if ! [[ "$node" =~ ^[1-4]$ ]]; then
            echo "ERROR: node must be 1, 2, 3, or 4"
            exit 1
        fi
        sudo journalctl -u "tos-validator@${node}" -f --no-pager
    else
        sudo journalctl -u "tos-dht" -u "tos-validator@1" -u "tos-validator@2" -u "tos-validator@3" -u "tos-validator@4" -f --no-pager
    fi
}

uninstall_services() {
    echo "Uninstalling TOS testnet services..."
    stop_services
    # Disable @5 too (a higher-numbered legacy unit) so a 4-node reinstall
    # doesn't leave the unit enabled-but-orphaned in multi-user.target.wants/.
    sudo systemctl disable tos-dht tos-validator@1 tos-validator@2 tos-validator@3 tos-validator@4 tos-validator@5 2>/dev/null || true
    sudo rm -f "$UNIT_DIR/tos-dht.service" "$UNIT_DIR/tos-validator@1.service" "$UNIT_DIR/tos-validator@2.service" "$UNIT_DIR/tos-validator@3.service" "$UNIT_DIR/tos-validator@4.service" "$UNIT_DIR/tos-validator@5.service" "$UNIT_DIR/tos-validator@.service"
    sudo systemctl daemon-reload
    echo "Services uninstalled."
}

case "${1:-help}" in
    install)   install_services ;;
    start)     start_services ;;
    stop)      stop_services ;;
    restart)   restart_services ;;
    status)    show_status ;;
    logs)      show_logs "${2:-}" ;;
    uninstall) uninstall_services ;;
    *)
        echo "Usage: $0 {install|start|stop|restart|status|logs [N]|uninstall}"
        exit 1
        ;;
esac
