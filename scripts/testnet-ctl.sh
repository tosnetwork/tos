#!/usr/bin/env bash
#
# testnet-ctl.sh - Manage local TOS testnet services
#
# Usage:
#   ./scripts/testnet-ctl.sh install   # install systemd units
#   ./scripts/testnet-ctl.sh start     # start all services
#   ./scripts/testnet-ctl.sh stop      # stop all services
#   ./scripts/testnet-ctl.sh restart   # restart all services
#   ./scripts/testnet-ctl.sh status    # show service status
#   ./scripts/testnet-ctl.sh logs [N]  # tail logs for validator N (default: all)
#   ./scripts/testnet-ctl.sh uninstall # stop and remove systemd units

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
UNIT_DIR="/etc/systemd/system"
PORTS_FILE="/data/testnet-ports.json"

validator_ids() {
    if [ -f "$PORTS_FILE" ]; then
        python3 -c "import json; print(' '.join(str(n['idx']) for n in json.load(open('$PORTS_FILE'))['nodes']))"
    else
        echo "1"
    fi
}

validator_services() {
    for id in $(validator_ids); do
        printf 'tos-validator@%s ' "$id"
    done
}

all_services() {
    printf 'tos-dht %s' "$(validator_services)"
}

install_services() {
    echo "Installing systemd unit files..."
    # Services are generated by setup-testnet.sh directly into /etc/systemd/system/
    sudo systemctl daemon-reload
    sudo systemctl enable $(all_services) 2>/dev/null || true
    echo "Services installed and enabled."
}

start_services() {
    echo "Starting TOS testnet..."
    sudo systemctl start tos-dht
    sleep 2  # give DHT time to bind
    sudo systemctl start $(validator_services)
    echo "All services started."
    sleep 1
    show_status
}

stop_services() {
    echo "Stopping TOS testnet..."
    for i in $(seq 20 -1 1); do
        sudo systemctl stop "tos-validator@$i" 2>/dev/null || true
    done
    sudo systemctl stop tos-dht 2>/dev/null || true
    echo "All services stopped."
}

restart_services() {
    stop_services
    sleep 1
    start_services
}

show_status() {
    for svc in $(all_services); do
        status=$(sudo systemctl is-active "$svc" 2>/dev/null || echo "inactive")
        printf "  %-24s %s\n" "$svc" "$status"
    done
}

show_logs() {
    local node="${1:-}"
    if [ -n "$node" ]; then
        if ! [[ "$node" =~ ^[0-9]+$ ]]; then
            echo "ERROR: node must be a positive integer"
            exit 1
        fi
        sudo journalctl -u "tos-validator@${node}" -f --no-pager
    else
        units=(-u tos-dht)
        for svc in $(validator_services); do
            units+=(-u "$svc")
        done
        sudo journalctl "${units[@]}" -f --no-pager
    fi
}

uninstall_services() {
    echo "Uninstalling TOS testnet services..."
    stop_services
    sudo systemctl disable tos-dht 2>/dev/null || true
    for i in $(seq 1 20); do
        sudo systemctl disable "tos-validator@$i" 2>/dev/null || true
        sudo rm -f "$UNIT_DIR/tos-validator@${i}.service"
    done
    sudo rm -f "$UNIT_DIR/tos-dht.service" "$UNIT_DIR/tos-validator@.service"
    sudo systemctl daemon-reload
    echo "Services uninstalled."
}

case "${1:-help}" in
    install)   install_services ;;
    start)     start_services ;;
    stop)      stop_services ;;
    restart)   restart_services ;;
    status)    show_status ;;
    logs)      show_logs "${2:-}" ;;
    uninstall) uninstall_services ;;
    *)
        echo "Usage: $0 {install|start|stop|restart|status|logs [N]|uninstall}"
        exit 1
        ;;
esac
