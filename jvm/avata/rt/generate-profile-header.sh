#!/bin/sh
set -eu

if [ "$#" -ne 3 ]; then
  echo "usage: $0 <api.jar> <jar-command> <output-header>" >&2
  exit 2
fi

api_jar=$1
jar_cmd=$2
output=$3

if [ ! -f "$api_jar" ]; then
  echo "profile header generation failed: missing $api_jar" >&2
  exit 2
fi

tmp="${output}.tmp"

classes=$("$jar_cmd" tf "$api_jar" | awk '
function deny_class(name) {
  return name == "java/io/FileDescriptor" \
      || name == "java/io/FileInputStream" \
      || name == "java/io/FileOutputStream" \
      || name == "java/io/FileNotFoundException" \
      || name == "java/io/FilterInputStream" \
      || name == "java/io/FilterOutputStream" \
      || name == "java/io/FilterReader" \
      || name == "java/io/LineNumberReader" \
      || name == "java/io/PushbackReader" \
      || name == "java/io/Serializable" \
      || name == "java/lang/ClassLoader" \
      || name == "java/lang/ClassNotFoundException" \
      || name == "java/lang/CloneNotSupportedException" \
      || name == "java/lang/Cloneable" \
      || name == "java/lang/ContractHex" \
      || name == "java/lang/IllegalAccessException" \
      || name == "java/lang/IllegalThreadStateException" \
      || name == "java/lang/InheritableThreadLocal" \
      || name == "java/lang/InterruptedException" \
      || name == "java/lang/NoSuchFieldException" \
      || name == "java/lang/NoSuchMethodException" \
      || name == "java/lang/Package" \
      || name == "java/lang/Process" \
      || name == "java/lang/ProcessBuilder" \
      || name == "java/lang/RoyaltySupport" \
      || name == "java/lang/Runtime" \
      || name == "java/lang/SecurityException" \
      || name == "java/lang/StringBuffer" \
      || name == "java/lang/Thread" \
      || name == "java/lang/ThreadDeath" \
      || name == "java/lang/ThreadGroup" \
      || name == "java/lang/ThreadLocal" \
      || name == "java/lang/TypeNotPresentException" \
      || name == "java/util/AbstractMap" \
      || name == "java/util/AbstractSequentialList" \
      || name == "java/util/EmptyStackException" \
      || name == "java/util/Enumeration" \
      || name == "java/util/EnumSet" \
      || name == "java/util/HashMap" \
      || name == "java/util/HashSet" \
      || name == "java/util/Hashtable" \
      || name == "java/util/IdentityHashMap" \
      || name == "java/util/LinkedHashMap" \
      || name == "java/util/LinkedHashSet" \
      || name == "java/util/NavigableMap" \
      || name == "java/util/Properties" \
      || name == "java/util/Stack" \
      || name == "java/util/StringTokenizer" \
      || name == "java/util/Vector" \
      || name == "java/util/WeakHashMap";
}

/\/$/ {
  next;
}

$0 ~ /^META-INF\// {
  next;
}

$0 !~ /\.class$/ {
  next;
}

{
  sub(/\.class$/, "", $0);
  if ($0 ~ /^java\/internal\//) {
    next;
  }
  if ($0 ~ /^java\/lang\/invoke\// \
      || $0 ~ /^java\/lang\/ref\// \
      || $0 ~ /^java\/lang\/reflect\// \
      || $0 ~ /^java\/net\// \
      || $0 ~ /^java\/nio\// \
      || $0 ~ /^java\/security\// \
      || $0 ~ /^java\/text\// \
      || $0 ~ /^java\/math\// \
      || $0 ~ /^java\/util\/concurrent\// \
      || $0 ~ /^java\/util\/jar\// \
      || $0 ~ /^java\/util\/logging\// \
      || $0 ~ /^java\/util\/regex\// \
      || $0 ~ /^java\/util\/zip\// \
      || $0 ~ /^javax\// \
      || $0 ~ /^sun\// \
      || $0 ~ /^avata\//) {
    next;
  }
  if (deny_class($0)) {
    next;
  }
  if ($0 ~ /\$/ && $0 != "java/util/Map$Entry") {
    next;
  }
  print;
}
' | LC_ALL=C sort -u)

{
  printf '%s\n' '/* Generated by rt/generate-profile-header.sh from api.jar.'
  printf '%s\n' '   Do not edit manually. */'
  printf '%s\n' ''
  printf '%s\n' '#ifndef AVATA_CONTRACT_PROFILE_H'
  printf '%s\n' '#define AVATA_CONTRACT_PROFILE_H'
  printf '%s\n' ''
  printf '%s\n' 'namespace vm {'
  printf '%s\n' ''
  printf '%s\n' 'static const char* const kContractProfileAdmittedApiClasses[] = {'
  printf '%s\n' "$classes" | awk 'NF {
    gsub(/\\/, "\\\\");
    gsub(/"/, "\\\"");
    printf "    \"%s\",\n", $0;
  }'
  printf '%s\n' '};'
  printf '%s\n' ''
  printf '%s\n' 'static const unsigned kContractProfileAdmittedApiClassCount'
  printf '%s\n' '    = sizeof(kContractProfileAdmittedApiClasses)'
  printf '%s\n' '      / sizeof(kContractProfileAdmittedApiClasses[0]);'
  printf '%s\n' ''
  printf '%s\n' '}  // namespace vm'
  printf '%s\n' ''
  printf '%s\n' '#endif  // AVATA_CONTRACT_PROFILE_H'
} > "$tmp"

mv "$tmp" "$output"
