"""Generate typed bindings from the frozen ordered schema; never regenerate fixtures."""
import argparse,hashlib,json,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
SCHEMA=ROOT/'doc/validator-auth-p0/canonical-schema.json'
schema=json.loads(SCHEMA.read_text());types=schema['types'];ordered=[];seen=set()
def name(t):return 'ApiError' if t=='error' else ''.join(x.capitalize() for x in t.split('_'))
def child(t):return t.split('/')[-1] if t.startswith('l') else t
def visit(t):
 if t not in types or t in seen:return
 for _,f in types[t]['fields']:visit(child(f))
 seen.add(t);ordered.append(t)
for t in types:visit(t)
def typ(t,lang):
 if t in types:return name(t)
 if t=='h':return 'Hash'
 if t.startswith('b'):return 'Bytes' if lang=='cpp' else 'Vec<u8>'
 if t.startswith('l'):return ('std::vector<'+typ(child(t),lang)+'>' if lang=='cpp' else 'Vec<'+typ(child(t),lang)+'>')
 return ('std::'+{'u8':'uint8_t','u16':'uint16_t','u32':'uint32_t','u64':'uint64_t','i32':'int32_t'}[t]) if lang=='cpp' else t
def minimum(t):
 if t in types:return (8 if types[t]['tag'] else 0)+sum(minimum(c) for _,c in types[t]['fields'])
 if t=='h':return 32
 if t.startswith('b'):return 4
 if t.startswith('l'):return int(t[1:].split('/')[0])//8
 return int(t[1:])//8
cpp=['// Generated by tools/validator-auth/generate.py; schema SHA256 '+hashlib.sha256(SCHEMA.read_bytes()).hexdigest(), '#pragma once','#include "codec.h"','namespace tos::auth {']
fingerprint=hashlib.sha256((ROOT/'doc/validator-auth-p0/profile.json').read_bytes()).digest()
cpp += ['inline constexpr Hash interface_fingerprint{'+','.join(str(b) for b in fingerprint)+'};']
rs=['// Generated by tools/validator-auth/generate.py.','use crate::codec::{Hash,Reader,Writer,Wire,Error};']
rs += ['pub const INTERFACE_FINGERPRINT: Hash = ['+','.join(str(b) for b in fingerprint)+'];']
for t in ordered:
 n=name(t);fields=types[t]['fields'];tag=types[t]['tag']
 cpp+=['struct '+n+' {']+[f'  {typ(c,"cpp")} {f}_{{}};' for f,c in fields]+[f'  bool operator==(const {n}&) const = default;','};']
 rs+=['#[derive(Clone, Debug, Default, PartialEq, Eq)]',f'pub struct {n} {{']+[f'    pub {f}: {typ(c,"rs")},' for f,c in fields]+['}']
 cpp +=[f'inline void read(Reader& r, {n}& v) {{']
 rs +=[f'impl Wire for {n} {{',f'    const MIN_SIZE: usize = {minimum(t)};', '    fn read(r: &mut Reader) -> Result<Self, Error> {']
 if tag:cpp +=[f'  r.header("{tag}");'];rs +=[f'        r.header(b"{tag}")?;']
 rs+=['        Ok(Self {']
 for f,c in fields:
  if c.startswith('l'):
   width,limit,_=c[1:].split('/');expr=f'r.list::<{typ(child(c),"rs")}>({int(width)//8}, {limit})?'
   cpp +=[f'  r.list(v.{f}_, {int(width)//8}, {limit}, {minimum(child(c))});']
  elif c.startswith('b'):cpp +=[f'  r.blob(v.{f}_, {c[1:]});'];expr=f'r.blob({c[1:]})?'
  elif c in types:cpp +=[f'  read(r, v.{f}_);'];expr=f'{name(c)}::read(r)?'
  elif c=='h':cpp +=[f'  r.hash(v.{f}_);'];expr='r.hash()?'
  else:cpp +=[f'  r.integer(v.{f}_);'];expr=f'r.integer({int(c[1:])//8})?'+('' if c=='u64' else f' as {c}')
  rs +=[f'            {f}: {expr},']
 cpp+=['}',f'inline void write(Writer& w, const {n}& v) {{']
 rs+=['        })','    }','    fn write(&self, w: &mut Writer) -> Result<(), Error> {']
 if tag:cpp +=[f'  w.header("{tag}");'];rs +=[f'        w.header(b"{tag}")?;']
 for f,c in fields:
  if c.startswith('l'):
   width,limit,_=c[1:].split('/');cpp +=[f'  w.list(v.{f}_, {int(width)//8}, {limit});'];expr=f'w.list(&self.{f}, {int(width)//8}, {limit})?'
  elif c.startswith('b'):cpp +=[f'  w.blob(v.{f}_, {c[1:]});'];expr=f'w.blob(&self.{f}, {c[1:]})?'
  elif c in types:cpp +=[f'  write(w, v.{f}_);'];expr=f'self.{f}.write(w)?'
  elif c=='h':cpp +=[f'  w.bytes(v.{f}_);'];expr=f'w.bytes(&self.{f})?'
  else:cpp +=[f'  w.integer(v.{f}_);'];expr=f'w.integer(self.{f}'+('' if c=='u64' else ' as u64')+f', {int(c[1:])//8})?'
  rs +=['        '+expr+';']
 cpp+=['}'];rs+=['        Ok(())','    }','}']
cpp+=['} // namespace tos::auth']
outputs={ROOT/'validator/auth/types.h':'\n'.join(cpp)+'\n',ROOT/'tosctl/src/validator-auth/src/types.rs':'\n'.join(rs)+'\n'}
outputs[ROOT/'test/validator-auth-implementation/dispatch.inc']='\n'.join('  if(kind=="'+t+'")return roundtrip<'+name(t)+'>(bytes,argv[4])?0:1;' for t in ordered)+'\n'
