outputs[ROOT/'crypto/block/validator-auth-profile.h']='\n'.join([
 '// Generated by tools/validator-auth/generate.py.', '#pragma once', '#include <array>', '#include <cstdint>',
 'namespace block {', 'inline constexpr std::array<std::uint8_t,32> validator_auth_profile_fingerprint{'+','.join(str(b) for b in fingerprint)+'};',
 '}'])+'\n'
