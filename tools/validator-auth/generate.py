api=['// Generated from the frozen method table.','#pragma once','#include "types.h"','namespace tos::auth {','inline Result<bool> validate_api_binary(std::uint8_t method, bool response, bool error, std::span<const std::uint8_t> raw) {','  if(method<1 || method>15)return Error{"method"};','  if(raw.size()>2000000)return Error{"api-binary-bound"};','  if(error){auto v=decode<ApiError>(raw);if(!v.ok())return v.error();return true;}','  switch(method){']
