#[derive(Clone, Debug, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct DeploymentSection {
    pub code_hash: String,
    pub address: String,
}

/// A JSON value read with every duplicate object key refused.
struct NoDuplicateKeys;

impl<'de> DeserializeSeed<'de> for NoDuplicateKeys {
    type Value = Value;
    fn deserialize<D: serde::Deserializer<'de>>(
        self,
        deserializer: D,
    ) -> std::result::Result<Value, D::Error> {
        deserializer.deserialize_any(self)
    }
}

impl<'de> Visitor<'de> for NoDuplicateKeys {
    type Value = Value;

    fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str("a JSON value")
    }
    fn visit_unit<E: serde::de::Error>(self) -> std::result::Result<Value, E> {
        Ok(Value::Null)
    }
    fn visit_bool<E: serde::de::Error>(self, value: bool) -> std::result::Result<Value, E> {
        Ok(Value::Bool(value))
    }
    fn visit_i64<E: serde::de::Error>(self, value: i64) -> std::result::Result<Value, E> {
        Ok(Value::Number(value.into()))
    }
    fn visit_u64<E: serde::de::Error>(self, value: u64) -> std::result::Result<Value, E> {
        Ok(Value::Number(value.into()))
    }
    fn visit_f64<E: serde::de::Error>(self, value: f64) -> std::result::Result<Value, E> {
        Number::from_f64(value)
            .map(Value::Number)
            .ok_or_else(|| E::custom("a number JSON cannot represent"))
    }
    fn visit_str<E: serde::de::Error>(self, value: &str) -> std::result::Result<Value, E> {
        Ok(Value::String(value.to_string()))
    }
    fn visit_string<E: serde::de::Error>(self, value: String) -> std::result::Result<Value, E> {
        Ok(Value::String(value))
    }
    fn visit_seq<A: SeqAccess<'de>>(self, mut seq: A) -> std::result::Result<Value, A::Error> {
        let mut items = Vec::new();
        while let Some(item) = seq.next_element_seed(NoDuplicateKeys)? {
            items.push(item);
        }
        Ok(Value::Array(items))
    }
    fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> std::result::Result<Value, A::Error> {
        let mut object = Map::new();
        while let Some(name) = map.next_key::<String>()? {
            if object.contains_key(&name) {
                return Err(A::Error::custom(format!("the field {name:?} appears twice")));
            }
            let value = map.next_value_seed(NoDuplicateKeys)?;
            object.insert(name, value);
        }
        Ok(Value::Object(object))
    }
}

/// Reads a manifest: well-formed JSON, no duplicate keys anywhere, and
/// exactly the fields a manifest has, nested where they belong.
pub fn parse(text: &str) -> Result<Manifest> {
    let malformed = |error: serde_json::Error| Error::Parameter(format!("manifest: {error}"));
    let mut deserializer = serde_json::Deserializer::from_str(text);
    let value = NoDuplicateKeys.deserialize(&mut deserializer).map_err(malformed)?;
    deserializer.end().map_err(malformed)?;
    serde_json::from_value(value).map_err(malformed)
}

/// Refuses a manifest that may not be deployed where funds are real.
///
/// It is held against the plan it claims to come from rather than read on its
/// own terms: a manifest is text anybody can edit, so "it says ceremony" is
/// worth nothing until the key, the state and the ceremony it names are the
/// ones that plan actually builds. Refused, each with its own reason:
///
/// * text that is not exactly a manifest -- malformed, a duplicate key, an
///   unknown or misplaced field;
/// * a development key class, or a plan that is a development one;
/// * a ceremony section that is missing, unfinished or not hexadecimal;
/// * the development verifying key, whatever the class says;
/// * a verifying key, ceremony, state or provenance other than the plan's;
/// * any remaining field that is not what rendering the plan produces,
///   including a deployment section for code other than `code`.
pub fn require_production(
    root: &std::path::Path,
    text: &str,
    plan: &Plan,
    code: Option<&Cell>,
) -> Result<()> {
    let manifest = parse(text)?;
    let refuse = |reason: String| Err(Error::Parameter(reason));

    let section = match (manifest.key.class.as_str(), &manifest.key.ceremony) {
        ("development", _) => {
            return refuse("this genesis carries the development verifying key".into())
        }
        ("ceremony", Some(section)) => section,
        ("ceremony", None) => {
            return refuse("this manifest says ceremony and names no ceremony".into())
        }
        (other, _) => {
            return refuse(format!("this manifest's key class {other:?} is not one there is"))
        }
    };
    let ceremony = match plan.key() {
        KeyClass::Ceremony(ceremony) => ceremony,
        KeyClass::Development => {
            return refuse("this genesis carries the development verifying key".into())
        }
    };

    if section.status != "finished" {
        return refuse(format!("the ceremony's status is {:?}, not finished", section.status));
    }
    for (name, value) in [
        ("transcript", &section.transcript),
        ("beacon_sha256", &section.beacon_sha256),
        ("phase1_slice_sha256", &section.phase1_slice_sha256),
        ("starting_key_sha256", &section.starting_key_sha256),
        ("key_sha256", &section.key_sha256),
        ("vk_sha256", &section.vk_sha256),
        ("groth16.vk_sha256", &manifest.groth16.vk_sha256),
        ("state.hash", &manifest.state.hash),
    ] {
        if !is_digest(value) {
            return refuse(format!("the manifest's {name} is not 64 lowercase hex digits"));
        }
    }

    let development = hex(&sha256(&development_parameters(root)?.verifying_key));
    if manifest.groth16.vk_sha256 == development || section.vk_sha256 == development {
        return refuse("this genesis carries the development verifying key".into());
    }

    let actual = hex(&sha256(&plan.parameters().verifying_key));
    if manifest.groth16.vk_sha256 != actual || section.vk_sha256 != actual {
        return refuse(format!(
            "the manifest names verifying key {} and the audited ceremony produced {actual}",
            manifest.groth16.vk_sha256
        ));
    }

    if !names(section, ceremony) {
        return refuse("the manifest names a different ceremony from the audited one".into());
    }

    let genesis = plan.build()?;
    let state = hex(&cell_hash(&genesis.state));
    if manifest.state.hash != state {
        return refuse(format!(
            "the manifest's state hash is {} and this plan builds {state}",
            manifest.state.hash
        ));
    }

    let provenance = plan.provenance();
    for (name, value) in [
        ("source_commit", &manifest.profile.source_commit),
        ("source_blob", &manifest.profile.source_blob),
    ] {
        if !is_object_id(value) {
            return refuse(format!("this manifest's {name} is not a git object id"));
        }
    }
    if manifest.profile.source_commit != provenance.source_commit
        || manifest.profile.source_blob != provenance.source_blob
    {
        return refuse("the manifest's profile provenance is not the plan's".into());
    }

    // Everything else: the manifest has to be what rendering this plan says,
    // field for field, so a descriptive field cannot lie beside a true hash.
    let expected = parse(&render(&genesis, provenance, plan.key(), code)?)?;
    if manifest != expected {
        return refuse("the manifest does not describe the genesis this plan builds".into());
    }
    Ok(())
}

/// Does the manifest's ceremony section say exactly what the audit found?
fn names(section: &CeremonySection, ceremony: &CeremonyKey) -> bool {
    let count = |value: usize| u64::try_from(value).ok();
    section.protocol == ceremony.protocol()
        && Some(section.steps) == count(ceremony.steps())
        && section.transcript == ceremony.transcript()
        && section.beacon_sha256 == ceremony.beacon_sha256()
        && section.phase1_transcript == ceremony.phase1_transcript()
        && section.phase1_slice_sha256 == ceremony.phase1_slice_sha256()
        && section.starting_key_sha256 == ceremony.starting_key_sha256()
        && Some(section.constraints) == count(ceremony.constraints())
        && Some(section.instance_variables) == count(ceremony.instance_variables())
        && section.key_sha256 == ceremony.key_sha256()
        && section.vk_sha256 == ceremony.vk_sha256()
}
