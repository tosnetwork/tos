//! The frozen manifest: what was deployed, and what it was built from.
//!
//! Section 13.2 is blunt about why this exists -- "a deployment fixture whose
//! initial state hash differs from the frozen generated manifest MUST fail".
//! The manifest is not documentation of the state; it is the thing a build is
//! checked against, so every field a reader might otherwise take on trust is
//! written down next to the hash it produced.

use chain_block::Cell;
use serde::de::{DeserializeSeed, Error as _, MapAccess, SeqAccess, Visitor};
use serde::Deserialize;
use serde_json::{Map, Number, Value};

use crate::{
    development_parameters, fr_be32, is_digest, is_object_id, profile_hash, sha256, CeremonyKey,
    Error, Genesis, KeyClass, Plan, Result,
};

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

/// A string as a JSON string literal, quotes and escapes included.
fn quoted(value: &str) -> Result<String> {
    serde_json::to_string(value).map_err(|error| Error::Encoding(error.to_string()))
}

/// The cell's own hash, which is what the state is identified by.
pub fn cell_hash(cell: &Cell) -> [u8; 32] {
    let mut out = [0u8; 32];
    out.copy_from_slice(cell.repr_hash().as_slice());
    out
}

/// Where the profile copy came from, so a reader can check it without
/// trusting this file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Provenance {
    /// The memo commit the profile was copied from.
    pub source_commit: String,
    /// The git blob id of the source file in that commit.
    pub source_blob: String,
}

/// Renders the manifest. JSON by hand rather than through a serialiser: the
/// field order is part of what is being frozen, and a derive would put that in
/// the gift of a dependency. Every string that did not come from this module
/// goes through [`quoted`], so no input can close a string and open a field.
pub fn render(
    genesis: &Genesis,
    provenance: &Provenance,
    key: &KeyClass,
    code: Option<&Cell>,
) -> Result<String> {
    let parameters = &genesis.parameters;
    let mut out = String::new();
    out.push_str("{\n");
    out.push_str("  \"note\": \"Generated by tools/shielded-pool-genesis. Section 13.2 of the V1 implementation profile. Do not edit by hand.\",\n");

    out.push_str("  \"profile\": {\n");
    out.push_str(&format!("    \"source_commit\": {},\n", quoted(&provenance.source_commit)?));
    out.push_str(&format!("    \"source_blob\": {},\n", quoted(&provenance.source_blob)?));
    out.push_str("    \"path\": \"artifacts/shielded-pool/PROFILE.md\",\n");
    out.push_str(&format!("    \"bytes\": {},\n", parameters.profile_bytes.len()));
    out.push_str(&format!(
        "    \"file_sha256\": \"{}\",\n",
        hex(&sha256(&parameters.profile_bytes))
    ));
    out.push_str(&format!(
        "    \"profile_hash\": \"{}\"\n",
        hex(&profile_hash(&parameters.profile_bytes))
    ));
    out.push_str("  },\n");

    out.push_str("  \"poseidon2\": {\n");
    out.push_str(&format!(
        "    \"manifest_bytes\": {},\n",
        parameters.poseidon_manifest_bytes.len()
    ));
    out.push_str(&format!(
        "    \"manifest_sha256\": \"{}\"\n",
        hex(&sha256(&parameters.poseidon_manifest_bytes))
    ));
    out.push_str("  },\n");

    out.push_str("  \"groth16\": {\n");
    out.push_str(&format!("    \"vk_bytes\": {},\n", parameters.verifying_key.len()));
    out.push_str(&format!("    \"vk_sha256\": \"{}\"\n", hex(&sha256(&parameters.verifying_key))));
    out.push_str("  },\n");

    // Machine-readable, so deployment tooling refuses a development state
    // instead of trusting someone to recognise its hash.
    out.push_str("  \"key\": {\n");
    match key {
        KeyClass::Development => out.push_str("    \"class\": \"development\"\n"),
        KeyClass::Ceremony(ceremony) => {
            out.push_str("    \"class\": \"ceremony\",\n");
            out.push_str("    \"ceremony\": {\n");
            out.push_str(&format!("      \"protocol\": {},\n", quoted(ceremony.protocol())?));
            out.push_str("      \"status\": \"finished\",\n");
            out.push_str(&format!("      \"steps\": {},\n", ceremony.steps()));
            out.push_str(&format!("      \"transcript\": {},\n", quoted(ceremony.transcript())?));
            out.push_str(&format!(
                "      \"beacon_sha256\": {},\n",
                quoted(ceremony.beacon_sha256())?
            ));
            out.push_str(&format!(
                "      \"phase1_transcript\": {},\n",
                quoted(ceremony.phase1_transcript())?
            ));
            out.push_str(&format!(
                "      \"phase1_slice_sha256\": {},\n",
                quoted(ceremony.phase1_slice_sha256())?
            ));
            out.push_str(&format!(
                "      \"starting_key_sha256\": {},\n",
                quoted(ceremony.starting_key_sha256())?
            ));
            out.push_str(&format!("      \"constraints\": {},\n", ceremony.constraints()));
            out.push_str(&format!(
                "      \"instance_variables\": {},\n",
                ceremony.instance_variables()
            ));
            out.push_str(&format!("      \"key_sha256\": {},\n", quoted(ceremony.key_sha256())?));
            out.push_str(&format!("      \"vk_sha256\": {}\n", quoted(ceremony.vk_sha256())?));
            out.push_str("    }\n");
        }
    }
    out.push_str("  },\n");

    out.push_str("  \"configuration\": {\n");
    out.push_str(&format!("    \"reserve_floor\": \"{}\",\n", parameters.reserve_floor));
    out.push_str(&format!("    \"withdrawal_fee\": \"{}\",\n", parameters.withdrawal_fee));
    out.push_str("    \"denominations\": [");
    for (position, amount) in parameters.denominations.iter().enumerate() {
        if position > 0 {
            out.push_str(", ");
        }
        out.push_str(&format!("\"{amount}\""));
    }
    out.push_str("]\n  },\n");

    out.push_str("  \"state\": {\n");
    out.push_str(&format!(
        "    \"commitment_root\": \"{}\",\n",
        hex(&fr_be32(genesis.commitment_root))
    ));
    out.push_str("    \"commitment_next_index\": 0,\n");
    out.push_str("    \"reserved_recovery_leaves\": 0,\n");
    out.push_str(&format!(
        "    \"nullifier_root\": \"{}\",\n",
        hex(&fr_be32(genesis.nullifier_root))
    ));
    out.push_str("    \"nullifier_next_index\": 1,\n");
    out.push_str(&format!("    \"last_anchor_epoch\": \"{:#010x}\",\n", crate::EPOCH_NONE));
    out.push_str("    \"native_liability\": \"0\",\n");
    out.push_str("    \"frontier\": \"twelve zero levels, seven slots each\",\n");
    out.push_str("    \"anchor_rings\": \"two empty dictionaries\",\n");
    out.push_str(&format!("    \"hash\": \"{}\"\n", hex(&cell_hash(&genesis.state))));
    out.push_str("  }");

    // The address only exists once there is code to hash with the state, and
    // the code is a build output rather than a protocol fact, so it is
    // optional and clearly labelled.
    if let Some(code) = code {
        out.push_str(",\n  \"deployment\": {\n");
        out.push_str(&format!("    \"code_hash\": \"{}\",\n", hex(&cell_hash(code))));
        out.push_str(&format!(
            "    \"address\": \"0:{}\"\n",
            hex(&crate::address(code, &genesis.state)?)
        ));
        out.push_str("  }");
    }
    out.push_str("\n}\n");
    Ok(out)
}

