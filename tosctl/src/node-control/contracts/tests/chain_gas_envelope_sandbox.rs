//! The gas envelope a contract will actually be given, taken from the zero
//! state this chain ships rather than from the executor's default table.
//!
//! These two disagreed, and the disagreement was not visible from either side.
//! `gen-zerostate.fif` grants a basechain transaction 30,000,000 gas;
//! `BlockchainConfig::default_with_global_version` grants it 1,000,000, which
//! is the value TON's basechain uses. A measurement taken against the default
//! therefore said a path "does not fit the network" when it fits this network
//! twenty-seven times over. That is not a number anyone can be expected to
//! remember, so it is asserted here: the zero state is generated by running
//! the real `create-state` over the real template, and the parameters the
//! executor hands to contracts are compared against what comes out.
//!
//! This test needs `build/crypto/create-state`, which `TOS_ROOT` locates.

use chain_block::{GasLimitsPrices, MsgForwardPrices};

const ACTIVE_VERSION: u32 = 18;

fn zerostate_config() -> chain_block::ConfigParams {
    let template =
        concat!(env!("CARGO_MANIFEST_DIR"), "/../../../../crypto/smartcont/gen-zerostate.fif");
    let state = tos_sandbox::generate_zerostate_state(template)
        .expect("generate the zero state (needs build/crypto/create-state)");
    state
        .read_custom()
        .expect("the masterchain extra")
        .expect("a masterchain zero state")
        .config
        .clone()
}

/// What the zero state grants, field by field, against what the executor's
/// default table grants. Every difference is named: a difference nobody named
/// is how a measurement ends up describing a chain that does not exist.
#[test]
fn the_executor_default_and_the_zero_state_grant_the_same_gas_envelope() {
    let zero = zerostate_config();
    let default = tos_executor::BlockchainConfig::default_with_global_version(ACTIVE_VERSION)
        .expect("a default configuration");

    let zero_wc: GasLimitsPrices = match zero.config(21).expect("param 21").expect("param 21") {
        chain_block::ConfigParamEnum::ConfigParam21(p) => p,
        other => panic!("parameter 21 is not gas prices: {other:?}"),
    };
    let default_wc = default.raw_config().gas_prices(false).expect("basechain gas prices");

    let rows: Vec<(&str, u64, u64)> = vec![
        ("gas_price", zero_wc.gas_price, default_wc.gas_price),
        ("gas_limit", zero_wc.gas_limit, default_wc.gas_limit),
        ("special_gas_limit", zero_wc.special_gas_limit, default_wc.special_gas_limit),
        ("gas_credit", zero_wc.gas_credit, default_wc.gas_credit),
        ("block_gas_limit", zero_wc.block_gas_limit, default_wc.block_gas_limit),
        ("flat_gas_limit", zero_wc.flat_gas_limit, default_wc.flat_gas_limit),
        ("flat_gas_price", zero_wc.flat_gas_price, default_wc.flat_gas_price),
    ];
    let mut differ = Vec::new();
    for (name, zero_value, default_value) in &rows {
        eprintln!("basechain {name:<18} zero state {zero_value:>12}  executor {default_value:>12}");
        if zero_value != default_value {
            differ.push(format!("{name}: zero state {zero_value}, executor {default_value}"));
        }
    }
    assert!(
        differ.is_empty(),
        "the executor grants a basechain transaction a different envelope from the one this \
         chain ships, so anything measured against it describes another chain:\n  {}",
        differ.join("\n  ")
    );

    let zero_mc: GasLimitsPrices = match zero.config(20).expect("param 20").expect("param 20") {
        chain_block::ConfigParamEnum::ConfigParam20(p) => p,
        other => panic!("parameter 20 is not gas prices: {other:?}"),
    };
    let default_mc = default.raw_config().gas_prices(true).expect("masterchain gas prices");
    assert_eq!(
        (zero_mc.gas_limit, zero_mc.special_gas_limit, zero_mc.block_gas_limit),
        (default_mc.gas_limit, default_mc.special_gas_limit, default_mc.block_gas_limit),
        "the masterchain envelopes disagree"
    );
}

/// The forward prices the same way. These were already aligned deliberately --
/// contracts read parameter 25 through GETFORWARDFEE, so a default that drifts
/// from the shipped table quietly invalidates every fee and reserve test -- and
/// the alignment is asserted rather than left to a comment.
#[test]
fn the_executor_default_and_the_zero_state_charge_the_same_to_forward() {
    let zero = zerostate_config();
    let default = tos_executor::BlockchainConfig::default_with_global_version(ACTIVE_VERSION)
        .expect("a default configuration");

    let zero_wc: MsgForwardPrices = match zero.config(25).expect("param 25").expect("param 25") {
        chain_block::ConfigParamEnum::ConfigParam25(p) => p,
        other => panic!("parameter 25 is not forward prices: {other:?}"),
    };
    let default_wc = default.raw_config().fwd_prices(false).expect("basechain forward prices");
    assert_eq!(
        (
            zero_wc.lump_price,
            zero_wc.bit_price,
            zero_wc.cell_price,
            zero_wc.first_frac,
            zero_wc.next_frac
        ),
        (
            default_wc.lump_price,
            default_wc.bit_price,
            default_wc.cell_price,
            default_wc.first_frac,
            default_wc.next_frac
        ),
        "the executor charges a different price to forward a message than this chain does"
    );
}

/// What this chain grants is not what TON's basechain grants, and that is a
/// choice rather than an accident. Pinning it here means a later alignment to
/// TON -- or a drift away from this number -- is a test to update and not a
/// surprise in a measurement.
#[test]
fn this_chains_basechain_grants_thirty_times_what_tons_does() {
    /// TON mainnet basechain, ConfigParam21, read from the live chain on
    /// 2026-09-20. Recorded for comparison only; nothing here uses it.
    const TON_BASECHAIN_GAS_LIMIT: u64 = 1_000_000;

    let zero = zerostate_config();
    let wc: GasLimitsPrices = match zero.config(21).expect("param 21").expect("param 21") {
        chain_block::ConfigParamEnum::ConfigParam21(p) => p,
        other => panic!("parameter 21 is not gas prices: {other:?}"),
    };
    assert_eq!(
        wc.gas_limit, 30_000_000,
        "this chain no longer grants a basechain transaction 30,000,000 gas"
    );
    assert_eq!(
        wc.gas_limit,
        TON_BASECHAIN_GAS_LIMIT * 30,
        "the ratio to TON's basechain has moved"
    );
    assert!(
        wc.block_gas_limit >= wc.gas_limit * 2,
        "a block ({}) no longer holds two transactions at the per-transaction limit ({})",
        wc.block_gas_limit,
        wc.gas_limit
    );
}
