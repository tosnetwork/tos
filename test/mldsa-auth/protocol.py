"""Explicit wire helpers for the native E2E suite, NOT a production wallet SDK."""
import functools
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'test/auth-extensions'))
from cells import Cell, from_boc

CONTEXT = b'TOS-AUTH-ML-DSA-44-v1'
SUBMIT = 0x4d4c4434
AUTH = 0x41555448


def chain(data):
    parts = [data[i:i + 127] for i in range(0, len(data), 127)] or [b'']
    tail = None
    for part in reversed(parts):
        node = Cell().raw(part)
        if tail is not None:
            node.ref(tail)
        tail = node
    return tail


def clone(cell):
    # Never mutate a Cell after its cached commitment was computed.
    return from_boc(cell.boc())


def commitment(request):
    return Cell().uint(0x544f532d41555448, 64).ref(request).hash


def module_data(public_key, network):
    if len(public_key) != 1312:
        raise ValueError('ML-DSA-44 public key must contain exactly 1312 bytes')
    return Cell().sint(network, 32).ref(chain(public_key))


def submission(envelope, signature, query_id=0):
    if len(signature) != 2420:
        raise ValueError('ML-DSA-44 signature must contain exactly 2420 bytes')
    return Cell().uint(SUBMIT, 32).uint(query_id, 64).ref(envelope).ref(chain(signature))


def parse_message(message):
    s = message.slice()
    assert s.uint(1) == 0, 'expected a real internal message'
    s.uint(1); bounce = s.uint(1); bounced = s.uint(1)
    sender, destination, value = s.addr(), s.addr(), s.coins()
    assert s.maybe() is None, 'no extra currencies in this profile'
    s.coins(); forward_fee = s.coins(); created_lt = s.uint(64); created_at = s.uint(32)
    assert s.uint(1) == 0, 'unexpected StateInit in relay/transfer'
    body = s.ref() if s.uint(1) else Cell(s.bits, s.refs)
    return {'sender': sender, 'destination': destination, 'value': value,
            'bounce': bounce, 'bounced': bounced, 'forward_fee': forward_fee,
            'created_lt': created_lt, 'created_at': created_at, 'body': body}


class Signer:
    """Deterministic, public TEST ONLY keys generated by the pinned C backend."""
    def __init__(self, executable):
        self.executable = str(Path(executable).resolve())

    @functools.lru_cache(maxsize=2048)
    def sign(self, message, context=CONTEXT, key=0):
        result = subprocess.run([self.executable, str(key), message.hex(), context.hex()],
                                text=True, capture_output=True, check=True)
        lines = result.stdout.splitlines()
        if len(lines) != 2:
            raise AssertionError('signer must emit exactly public key and signature')
        public_key, signature = (bytes.fromhex(line) for line in lines)
        assert len(public_key) == 1312 and len(signature) == 2420
        return public_key, signature

    def public_key(self, key=0):
        return self.sign(b'', key=key)[0]
