"""Generates the Rust VM's codepage 0 prefix table from the C++ VM's (test-vm-opcode-table).

The C++ VM looks up at most 24 bits of code, padded with zeros, in its finalized codepage 0 and
decides from the range found whether an instruction may run: an unassigned opcode or one the
global version does not enable is invalid (10 gas); otherwise its prefix width is charged as base
gas and that many bits must be present. The Rust VM checks the same table before running a
handler (engine/cp0_prefixes.rs). Adjacent ranges with the same prefix are merged.

Usage:
    vm_opcode_table.py <table.tsv> <out.rs>      write the Rust table
    vm_opcode_table.py <table.tsv> --check       fail unless the committed table is up to date
    vm_opcode_table.py <table.tsv> --tsv <out>   write the merged ranges as TSV
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUST = ROOT / "tosctl/src/vm/src/executor/engine/cp0_prefixes.rs"
TOP = 1 << 24


def read(path):
    """Ranges (first, bits, version) from the tool's output; bits 0 marks an unassigned range."""
    ranges = []
    for n, line in enumerate(Path(path).read_text().splitlines(), 1):
        fields = line.split("\t")
        if len(fields) != 4:
            sys.exit(f"{path}:{n}: expected 4 fields")
        first, assigned, bits, version = (
            int(fields[0], 16),
            fields[1],
            int(fields[2]),
            int(fields[3]),
        )
        if assigned not in ("0", "1") or not 0 <= first < TOP:
            sys.exit(f"{path}:{n}: malformed range")
        if assigned == "1" and not 0 < bits <= 24:
            sys.exit(f"{path}:{n}: an assigned range needs 1..24 prefix bits")
        if assigned == "0":
            bits = version = 0
        if not 0 <= version < 256:
            sys.exit(f"{path}:{n}: version {version} out of range")
        if ranges and first <= ranges[-1][0]:
            sys.exit(f"{path}:{n}: ranges out of order")
        if not ranges and first != 0:
            sys.exit(f"{path}:{n}: the table must start at opcode 0")
        ranges.append((first, bits, version))
    if not ranges:
        sys.exit(f"{path}: empty table")
    merged = []
    for r in ranges:
        if merged and merged[-1][1:] == r[1:]:
            continue
        merged.append(r)
    return merged


def rust(ranges):
    lines = [
        "// Generated by test/rescue-fee-gate/vm_opcode_table.py from the C++ VM's codepage 0",
        "// (test-vm-opcode-table); do not edit. CI regenerates it and fails on any difference.",
        "//",
        "// Each entry starts a range of 24-bit opcodes that runs to the next entry's start:",
        "// (first opcode, prefix bits, version). 0 prefix bits marks unassigned opcodes.",
        f"pub(super) const CP0_PREFIXES: [(u32, u8, u8); {len(ranges)}] = [",
    ]
    lines += [f"    (0x{first:06x}, {bits}, {version})," for first, bits, version in ranges]
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(args):
    if len(args) == 2 and args[1] == "--check":
        if RUST.read_text() != rust(read(args[0])):
            sys.exit(f"{RUST.relative_to(ROOT)} differs from the C++ table: regenerate it")
        print(f"{RUST.relative_to(ROOT)}: up to date")
    elif len(args) == 3 and args[1] == "--tsv":
        ranges = read(args[0])
        Path(args[2]).write_text("".join(f"{f:06x}\t{b}\t{v}\n" for f, b, v in ranges))
    elif len(args) == 2:
        ranges = read(args[0])
        Path(args[1]).write_text(rust(ranges))
        print(f"{len(ranges)} ranges")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
