    # Contribution 1's document, validly signed, moved into position 2.
    one = (setup["attestations"] / "attestation-1.txt").read_text()
    target = setup["attestations"] / "attestation-2.txt"
    target.write_text(one)
    sign(setup["outsider"], target)
    return "a valid document moved to another position", "says it is contribution 1", run(setup), None


