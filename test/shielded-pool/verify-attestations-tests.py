def case_waiver_does_not_rescue_independence(scratch: Path) -> tuple:
    """Waiving a signature must not also waive rule 4.

    The waiver exists so a ceremony can deliberately carry a contribution
    nobody stands behind. If it silently satisfied the independence rule too,
    the loudest way to weaken the ceremony would also be the way to switch off
    the check that notices.
    """
    setup = build(scratch, outsider_independent=False)
    (setup["attestations"] / "attestation-2.txt.sig").unlink()
    return (
        "a waived signature does not satisfy the independence rule",
        "no verified contribution comes from a participant declared independent",
        run(setup, "--unattested-ok", "2"),
        None,
    )


