#!/usr/bin/env python3
"""Proof that the attestation verifier can fail.

A verifier that accepts everything and a verifier that works are
indistinguishable on a ceremony where nothing is wrong, and the ceremony this
one guards will have nothing wrong with it by the time anybody looks. So each
case below breaks exactly one thing and requires the refusal to **name that
thing** -- not merely to be a refusal, because any error at all makes a
"it refused" assertion pass, including an error in this file's own setup.

That failure mode is not hypothetical here: the fixtures are built by hand, so
a typo in the scaffolding produces a refusal for the wrong reason and a green
suite.

ON THE KEYS USED HERE

    Two throwaway ed25519 keys are generated into a temporary directory and
    deleted with it. They exist to prove the signature check distinguishes a
    key on the roster from one that is not; neither is ever placed in a real
    roster, and a key generated by a test is exactly the kind of identity the
    ceremony refuses from a participant -- which is the property under test.
"""

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
VERIFIER = HERE / "verify-attestations.py"
PROTOCOL = "tos-shielded-pool-v1-phase2"
GPG = shutil.which("gpg")

START = "a" * 64
C1 = "1" * 64
T1 = "2" * 64
C2 = "3" * 64
T2 = "4" * 64
COMMIT = "b" * 40


def document(index: int, contribution: str, transcript: str, start: str = START) -> str:
    return (
        f"TOS shielded pool, phase 2 -- contribution {index}\n"
        "\n"
        "I drew a scalar from my machine's random generator, applied it, and\n"
        "destroyed it. I do not have it.\n"
        "\n"
        f"  built from     {COMMIT}\n"
        f"  starting key   {start}\n"
        f"  contribution   {contribution}\n"
        f"  transcript     {transcript}\n"
    )


def record() -> dict:
    return {
        "protocol": PROTOCOL,
        "phase1_transcript": "zcash",
        "phase1_slice_sha256": "c" * 64,
        "constraints": 18107,
        "instance_variables": 19,
        "starting_key_sha256": START,
        "entries": [
            {"index": 1, "kind": "participant", "sha256": C1, "transcript_after": T1},
            {"index": 2, "kind": "participant", "sha256": C2, "transcript_after": T2},
        ],
        "key_sha256": "d" * 64,
        "transcript": T2,
    }


def keygen(path: Path) -> str:
    """A throwaway signing key. Returns its public half."""
    subprocess.run(
        ["ssh-keygen", "-t", "ed25519", "-N", "", "-C", "throwaway", "-f", str(path)],
        check=True,
        capture_output=True,
    )
    return path.with_suffix(".pub").read_text().strip()


def sign(key: Path, document_path: Path) -> None:
    # stdin from /dev/null, not inherited. `ssh-keygen -Y sign` falls back to
    # prompting for a passphrase, and with an inherited stdin that prompt is a
    # silent hang rather than an error -- observed here as a thirty-two minute
    # wait in a suite that normally finishes in twenty seconds.
    subprocess.run(
        ["ssh-keygen", "-Y", "sign", "-f", str(key), "-n", "file", str(document_path)],
        check=True,
        capture_output=True,
        stdin=subprocess.DEVNULL,
        timeout=60,
    )


def gpg_keygen(home: Path, uid: str) -> tuple:
    """A throwaway pgp key in its own home. Returns (fingerprint, armoured key).

    Same reasoning as the ssh keys above: it exists to show the pgp branch
    distinguishes a roster key from a stranger's, and it is deleted with the
    temporary directory. The pgp branch is exercised because the contribution
    script offers `--sign-with gpg:`, and a signing path with no verifier test
    is a path that fails for the first participant who uses it.
    """
    home.mkdir(mode=0o700, parents=True, exist_ok=True)
    env = {"GNUPGHOME": str(home), "PATH": "/usr/bin:/bin", "LC_ALL": "C"}
    subprocess.run(
        [
            GPG, "--batch", "--pinentry-mode", "loopback", "--passphrase", "",
            "--quick-generate-key", uid, "ed25519", "sign", "0",
        ],
        check=True,
        capture_output=True,
        stdin=subprocess.DEVNULL,
        timeout=120,
        env=env,
    )
    listed = subprocess.run(
        [GPG, "--list-secret-keys", "--with-colons"],
        check=True,
        capture_output=True,
        text=True,
        env=env,
    )
    fingerprint = next(
        line.split(":")[9] for line in listed.stdout.splitlines() if line.startswith("fpr:")
    )
    armoured = subprocess.run(
        [GPG, "--armor", "--export", fingerprint],
        check=True,
        capture_output=True,
        text=True,
        env=env,
    ).stdout
    return fingerprint, armoured


def gpg_clearsign(home: Path, fingerprint: str, document_path: Path) -> None:
    env = {"GNUPGHOME": str(home), "PATH": "/usr/bin:/bin", "LC_ALL": "C"}
    subprocess.run(
        [
            GPG, "--batch", "--pinentry-mode", "loopback", "--passphrase", "",
            "--local-user", fingerprint, "--clearsign",
            "--output", str(document_path) + ".asc", str(document_path),
        ],
        check=True,
        capture_output=True,
        stdin=subprocess.DEVNULL,
        timeout=120,
        env=env,
    )


def build_gpg(scratch: Path) -> dict:
    """The same two-contribution ceremony, with contribution 2 signed by pgp."""
    setup = build(scratch)
    home = scratch / "gnupg"
    fingerprint, armoured = gpg_keygen(home, "Outside Participant <out@example.invalid>")

    two = setup["attestations"] / "attestation-2.txt"
    (setup["attestations"] / "attestation-2.txt.sig").unlink()
    gpg_clearsign(home, fingerprint, two)

    roster_data = json.loads(setup["roster"].read_text())
    roster_data["participants"][1]["key"] = {
        "type": "gpg",
        "fingerprint": fingerprint,
        "public_key": armoured,
    }
    setup["roster"].write_text(json.dumps(roster_data, indent=2))
    setup["gnupg"] = home
    setup["gpg_fingerprint"] = fingerprint
    return setup


def case_gpg_intact(scratch: Path) -> tuple:
    setup = build_gpg(scratch)
    result = run(setup)
    if result.returncode != 0:
        return "a pgp-signed contribution is accepted", None, result, "accepted"
    if "the outside participant" not in result.stdout:
        return "a pgp-signed contribution is accepted", None, result, "names the outsider"
    return "a pgp-signed contribution is accepted", None, result, None


def case_gpg_stranger(scratch: Path) -> tuple:
    setup = build_gpg(scratch)
    stranger_home = scratch / "gnupg-stranger"
    stranger_fpr, _ = gpg_keygen(stranger_home, "Stranger <s@example.invalid>")
    two = setup["attestations"] / "attestation-2.txt"
    (setup["attestations"] / "attestation-2.txt.asc").unlink()
    gpg_clearsign(stranger_home, stranger_fpr, two)
    return (
        "a pgp signature from a key nobody published",
        "does not verify against the roster's keys",
        run(setup),
        None,
    )


def case_gpg_over_something_else(scratch: Path) -> tuple:
    setup = build_gpg(scratch)
    decoy = setup["attestations"] / "decoy.txt"
    decoy.write_text(document(2, C2, T2) + "\nand also I own the moon\n")
    gpg_clearsign(setup["gnupg"], setup["gpg_fingerprint"], decoy)
    shutil.move(
        str(setup["attestations"] / "decoy.txt.asc"),
        str(setup["attestations"] / "attestation-2.txt.asc"),
    )
    decoy.unlink()
    return (
        "a real pgp signature over different bytes",
        "valid signature over something other than",
        run(setup),
        None,
    )


def case_gpg_without_fingerprint(scratch: Path) -> tuple:
    setup = build_gpg(scratch)
    roster_data = json.loads(setup["roster"].read_text())
    del roster_data["participants"][1]["key"]["fingerprint"]
    setup["roster"].write_text(json.dumps(roster_data, indent=2))
    return (
        "a pgp roster entry with no fingerprint",
        "no 40-character fingerprint",
        run(setup),
        None,
    )


def roster(insider_key: str, outsider_key: str, outsider_independent: bool = True) -> dict:
    return {
        "protocol": PROTOCOL,
        "participants": [
            {
                "name": "the operator",
                "independent_of_operator": False,
                "key": {
                    "type": "ssh",
                    "principal": "operator@example.invalid",
                    "public_key": insider_key,
                },
            },
            {
                "name": "the outside participant",
                "independent_of_operator": outsider_independent,
                "key": {
                    "type": "ssh",
                    "principal": "outsider@example.invalid",
                    "public_key": outsider_key,
                },
            },
        ],
    }


def build(scratch: Path, *, outsider_independent: bool = True) -> dict:
    """A ceremony that passes, so each case can break one thing about it."""
    ceremony = scratch / "ceremony"
    ceremony.mkdir()
    (ceremony / "ceremony.json").write_text(json.dumps(record(), indent=2))

    keys = scratch / "keys"
    keys.mkdir()
    insider = keys / "insider"
    outsider = keys / "outsider"
    insider_pub = keygen(insider)
    outsider_pub = keygen(outsider)

    attestations = scratch / "attestations"
    attestations.mkdir()
    one = attestations / "attestation-1.txt"
    two = attestations / "attestation-2.txt"
    one.write_text(document(1, C1, T1))
    two.write_text(document(2, C2, T2))
    sign(insider, one)
    sign(outsider, two)

    roster_path = scratch / "roster.json"
    roster_path.write_text(
        json.dumps(roster(insider_pub, outsider_pub, outsider_independent), indent=2)
    )

    return {
        "ceremony": ceremony,
        "attestations": attestations,
        "roster": roster_path,
        "keys": keys,
        "insider": insider,
        "outsider": outsider,
        "insider_pub": insider_pub,
        "outsider_pub": outsider_pub,
    }


def run(setup: dict, *extra: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [
            sys.executable,
            str(VERIFIER),
            str(setup["ceremony"]),
            "--roster",
            str(setup["roster"]),
            "--attestations",
            str(setup["attestations"]),
            *extra,
        ],
        capture_output=True,
        text=True,
    )


