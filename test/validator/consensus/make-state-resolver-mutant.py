#!/usr/bin/env python3
"""Generate the test-only mutant of the Simplex state resolver.

The Merkle actor test proves its fixtures can fail by running them against a resolver that
picks the wrong base. The mutant is the production state-resolver.cpp with two hooks
inserted, each a call into the test driver:

  * before an exact ancestor is resolved, the driver may substitute a different ancestor
    (the skip shortcut that let local skip evidence replace a signed parent, or a sibling
    at the same height);
  * when a finalized anchor is not yet available from the manager, the driver may make the
    resolver fall back to the session's start state instead of reconstructing the anchor.

Only the test executable built from this output links the mutant; the production resolver
is never changed. Every insertion point must occur exactly once, so a refactor of the
resolver stops this script instead of silently producing an unmutated copy.
"""

import sys
from pathlib import Path

NAMESPACE_OPEN = "namespace tos::validator::consensus::simplex {\n"
HOOK_DECLARATIONS = """
// Test-only hooks, defined by the Merkle actor test driver.
std::optional<ParentId> state_resolver_mutant_substitute(const ParentId& id);
bool state_resolver_mutant_stale_anchor();
"""

EXACT_ANCESTOR = (
    "      auto resolved_candidate = co_await owning_bus().publish<ResolveCandidate>(*id).wrap();\n"
)
SUBSTITUTE = """      if (auto substitute = state_resolver_mutant_substitute(id)) {
        id = *substitute;
        continue;
      }
"""

ANCHOR_UNAVAILABLE = '        LOG(WARNING) << "Simplex state-resolver: finalized anchor " << *id\n'
STALE_ANCHOR = """        if (state_resolver_mutant_stale_anchor()) {
          state = genesis->state;
          break;
        }
"""


def insert_before(source: str, anchor: str, text: str) -> str:
    count = source.count(anchor)
    if count != 1:
        raise SystemExit(
            f"make-state-resolver-mutant: anchor occurs {count} times, not once: {anchor!r}"
        )
    return source.replace(anchor, text + anchor)


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: make-state-resolver-mutant.py <state-resolver.cpp> <output>")
    source = Path(sys.argv[1]).read_text()
    count = source.count(NAMESPACE_OPEN)
    if count != 1:
        raise SystemExit(f"make-state-resolver-mutant: namespace opens {count} times, not once")
    source = source.replace(NAMESPACE_OPEN, NAMESPACE_OPEN + HOOK_DECLARATIONS)
    source = insert_before(source, EXACT_ANCESTOR, SUBSTITUTE)
    source = insert_before(source, ANCHOR_UNAVAILABLE, STALE_ANCHOR)
    header = (
        "// Generated by test/validator/consensus/make-state-resolver-mutant.py from\n"
        "// validator/consensus/simplex/state-resolver.cpp. Test-only; do not edit.\n"
    )
    out = Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + source)


if __name__ == "__main__":
    main()
