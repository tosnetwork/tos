"""Take the inputs of the Rust node's cryptographic vector families as crypto-harness contexts.

    crypto_rtos.py contexts <rtos-data-dir> <out-dir>
        Write <family>.contexts.jsonl. Only inputs are taken; every effect is refilled from the C++
        reference by ``conformance.py create``.
    crypto_rtos.py compare <rtos-data-dir> <fixtures-dir>
        Compare the C++ refill with the expectations frozen in the Rust tree, row for row, and print
        every disagreement. Those expectations were themselves filled by an older C++ build, so a
        disagreement is either a C++ behaviour change since then or a conversion error here.

<rtos-data-dir> holds these files of the Rust tree, flat (``git show <commit>:<path>``):

    pq-crypto/tests/data/lms-fee.tsv               id verdict cost message signature key
    pq-crypto/tests/data/falcon512.tsv             id verdict message signature key
    pq-crypto/tests/data/verification-vectors.tsv  id verdict message context signature key (ML-DSA-44)
    pq-crypto/tests/data/simplex-context.json      one key and message, signatures under three contexts
    pq-crypto/tests/data/slhdsa128s-boundaries.tsv id result (0 invalid, 1 valid, 2 refused)
    pq-crypto/tests/data/slhdsa128s-{acvp,circl,other-profiles}.json  the boundary matrix's bases
    block/tests/data/quorum-vectors.txt            total threshold

The boundary matrix's mutated cases are not stored in the Rust tree; they are generated by its test
(pq-crypto/tests/slhdsa128s.rs, frozen_cpp_boundary_matrix) from the bases. Here each one is the base
plus ``edits`` that make the same change, so the 7,856-byte signature is stored once.
"""

from __future__ import annotations

import json
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any, cast

# Run as a script from its own directory, next to the shared helpers.
sys.path.insert(0, str(Path(__file__).resolve().parent))

from crypto_common import (  # noqa: E402
    Checker,
    Json,
    ctx,
    entry,
    hexb,
    load_fixtures,
    write_contexts,
)

VERDICT_LETTER = {"valid": "V", "invalid": "I", "malformed_input": "M", "backend_error": "B"}
SLH_CODE = {"valid": "1", "invalid": "0", "malformed_input": "2", "backend_error": "backend"}
SLH_FIELDS = ("message", "context", "signature", "public_key")
SLH_BASES = ("slhdsa128s-acvp.json", "slhdsa128s-circl.json", "slhdsa128s-other-profiles.json")


def tsv(path: Path) -> list[list[str]]:
    return [line.split("\t") for line in path.read_text().splitlines() if line]


def contexts_lms(data: Path) -> list[Json]:
    out: list[Json] = []
    for row in tsv(data / "lms-fee.tsv"):
        name, _verdict, _cost, message, signature, key = row
        inputs = {"message": hexb(message), "signature": hexb(signature), "public_key": hexb(key)}
        out.append(entry(name, ctx("lms_fee", "verify", inputs)))
        cost = {"public_key": hexb(key), "message_bytes": str(len(message) // 2)}
        out.append(entry(f"{name}.cost", ctx("lms_fee", "worst_compressions", cost)))
    return out


def contexts_falcon(data: Path) -> list[Json]:
    return [
        entry(
            name,
            ctx(
                "falcon512",
                "verify_padded",
                {"message": hexb(message), "signature": hexb(signature), "public_key": hexb(key)},
            ),
        )
        for name, _verdict, message, signature, key in tsv(data / "falcon512.tsv")
    ]


def contexts_mldsa(data: Path) -> list[Json]:
    out: list[Json] = []
    for name, _verdict, message, context, signature, key in tsv(data / "verification-vectors.tsv"):
        inputs = {
            "message": hexb(message),
            "context": hexb(context),
            "signature": hexb(signature),
            "public_key": hexb(key),
        }
        out.append(entry(name, ctx("mldsa44", "verify", inputs)))
    return out


def contexts_simplex(data: Path) -> list[Json]:
    doc = cast(Json, json.loads((data / "simplex-context.json").read_text()))
    message, key = hexb(doc["messageHex"]), hexb(doc["publicKeyHex"])
    out: list[Json] = []
    for case in cast(list[Json], doc["cases"]):
        signature = hexb(case["signatureHex"])
        own = {
            "message": message,
            "context": hexb(case["contextHex"]),
            "signature": signature,
            "public_key": key,
        }
        out.append(entry(f"{case['id']}.own-context", ctx("mldsa44", "verify", own)))
        simplex = {
            "surface": "simplex",
            "message": message,
            "signature": signature,
            "public_key": key,
        }
        out.append(entry(f"{case['id']}.simplex", ctx("mldsa44", "verify_consensus", simplex)))
    return out


def slh_bases(data: Path) -> dict[str, Json]:
    bases: dict[str, Json] = {}
    for name in SLH_BASES:
        for row in cast(list[Json], json.loads((data / name).read_text())):
            bases[row["id"]] = {field: hexb(row[field]) for field in SLH_FIELDS}
    return bases


def slh_matrix(data: Path) -> list[tuple[str, str, list[Json]]]:
    """(case id, base id, edits) in the order frozen_cpp_boundary_matrix runs them."""
    cases: list[tuple[str, str, list[Json]]] = [
        (name, name, []) for name in sorted(slh_bases(data))
    ]
    flips = [
        ("signature-byte", "circl-m0-c0", "signature", list(range(7856))),
        ("key-byte", "circl-m0-c0", "public_key", list(range(32))),
        ("context-byte", "circl-m1-c255", "context", list(range(255))),
        ("message-byte", "circl-m8192-c0", "message", [*range(0, 8192, 64), 8191]),
    ]
    for prefix, base, field, offsets in flips:
        for offset in offsets:
            cases.append(
                (
                    f"{prefix}-{offset}",
                    base,
                    [{"input": field, "op": "xor", "offset": offset, "value": 1}],
                )
            )
    lengths = [
        (3, [0, 1, 15, 16, 31, 33, 64]),
        (2, [0, 1, 15, 16, 7839, 7840, 7855, 7857, 8192]),
        (0, [8193, 8194]),
        (1, [256, 257]),
    ]
    for index, sizes in lengths:
        for size in sizes:
            edit = {"input": SLH_FIELDS[index], "op": "resize", "length": size, "value": 0}
            cases.append((f"length-{index}-{size}", "circl-m8192-c255", [edit]))
    for index in range(4):
        for label, byte in (("zero", 0), ("ff", 255)):
            edit = {"input": SLH_FIELDS[index], "op": "fill", "value": byte}
            cases.append((f"{label}-{index}", "circl-m1-c255", [edit]))
    return cases


def contexts_slh(data: Path) -> list[Json]:
    bases = slh_bases(data)
    return [
        entry(
            name,
            ctx("slhdsa128s", "verify", bases[base], edits),
            None if not edits else f"base {base}",
        )
        for name, base, edits in slh_matrix(data)
    ]


def contexts_quorum(data: Path) -> list[Json]:
    out: list[Json] = []
    for line in (data / "quorum-vectors.txt").read_text().splitlines():
        total, _threshold = line.split(" ")
        out.append(entry(f"total-{total}", ctx("quorum", "threshold", {"total_weight": total})))
    return out


FAMILIES: dict[str, Callable[[Path], list[Json]]] = {
    "rtos-lms-fee": contexts_lms,
    "rtos-falcon512": contexts_falcon,
    "rtos-mldsa44-verification": contexts_mldsa,
    "rtos-simplex-context": contexts_simplex,
    "rtos-slhdsa128s-boundaries": contexts_slh,
    "rtos-quorum": contexts_quorum,
}


# ---------------------------------------------------------------------------------------------


def verdict_of(effects: Json | None, table: dict[str, str]) -> str:
    if effects is None:
        return "<no fixture>"
    if effects.get("outcome") != "verdict":
        return f"<{effects.get('outcome')}>"
    return table[cast(str, effects["verdict"])]


def get(fixtures: dict[str, Json], name: str) -> Json | None:
    fixture = fixtures.get(name)
    return None if fixture is None else cast(Json, fixture["effects"])


def compare(data: Path, fixtures_dir: Path) -> int:
    differences = 0

    def family(name: str) -> dict[str, Json]:
        return load_fixtures(fixtures_dir / f"{name}.jsonl")

    c = Checker("rtos-lms-fee")
    fx = family("rtos-lms-fee")
    for name, verdict, cost, *_ in tsv(data / "lms-fee.tsv"):
        c.expect(name, verdict, verdict_of(get(fx, name), VERDICT_LETTER))
        effects = get(fx, f"{name}.cost") or {}
        actual = effects.get("value") if effects.get("outcome") == "integer" else "-"
        c.expect(f"{name}.cost", cost, actual)
    differences += c.done()

    c = Checker("rtos-falcon512")
    fx = family("rtos-falcon512")
    for name, verdict, *_ in tsv(data / "falcon512.tsv"):
        c.expect(name, verdict, verdict_of(get(fx, name), VERDICT_LETTER))
    differences += c.done()

    c = Checker("rtos-mldsa44-verification")
    fx = family("rtos-mldsa44-verification")
    for name, verdict, *_ in tsv(data / "verification-vectors.tsv"):
        c.expect(name, verdict, verdict_of(get(fx, name), VERDICT_LETTER))
    differences += c.done()

    c = Checker("rtos-simplex-context")
    fx = family("rtos-simplex-context")
    doc = cast(Json, json.loads((data / "simplex-context.json").read_text()))
    for case in cast(list[Json], doc["cases"]):
        # The Rust test: every signature verifies under its own context, and only the simplex one
        # under the consensus domain.
        c.expect(
            f"{case['id']}.own-context",
            "V",
            verdict_of(get(fx, f"{case['id']}.own-context"), VERDICT_LETTER),
        )
        expected = "V" if case["id"] == "simplex" else "I"
        c.expect(
            f"{case['id']}.simplex",
            expected,
            verdict_of(get(fx, f"{case['id']}.simplex"), VERDICT_LETTER),
        )
    differences += c.done()

    c = Checker("rtos-slhdsa128s-boundaries")
    fx = family("rtos-slhdsa128s-boundaries")
    frozen = dict(
        line.split("\t") for line in (data / "slhdsa128s-boundaries.tsv").read_text().splitlines()
    )
    names = [name for name, _base, _edits in slh_matrix(data)]
    if sorted(names) != sorted(frozen):
        print(
            f"DIFF rtos-slhdsa128s-boundaries: generated {len(names)} cases, frozen {len(frozen)}"
        )
        differences += 1
    for name in names:
        c.expect(name, frozen.get(name), verdict_of(get(fx, name), SLH_CODE))
    for base_file in SLH_BASES[:2]:
        for row in cast(list[Any], json.loads((data / base_file).read_text())):
            # The upstream answer travels with ACVP and CIRCL rows; a wrong-length signature is
            # refused before verification rather than answered.
            item = cast(Json, row)
            expected = "valid" if item["expected"] else "invalid"
            if len(item["signature"]) != 2 * 7856:
                expected = "malformed_input"
            got = get(fx, cast(str, item["id"])) or {}
            c.expect(f"{item['id']}.upstream", expected, got.get("verdict"))
    differences += c.done()

    c = Checker("rtos-quorum")
    fx = family("rtos-quorum")
    for line in (data / "quorum-vectors.txt").read_text().splitlines():
        total, threshold = line.split(" ")
        effects = get(fx, f"total-{total}") or {}
        c.expect(f"total-{total}", threshold, effects.get("value"))
    differences += c.done()

    print(f"total differences {differences}")
    return 1 if differences else 0


def main(argv: list[str]) -> int:
    if len(argv) == 3 and argv[0] == "contexts":
        data, out = Path(argv[1]), Path(argv[2])
        for name, fn in FAMILIES.items():
            print(f"{name}: {write_contexts(out / f'{name}.contexts.jsonl', fn(data))} contexts")
        return 0
    if len(argv) == 3 and argv[0] == "compare":
        return compare(Path(argv[1]), Path(argv[2]))
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
