// Evidence experiment against committed host 880fc7f7a; no deletion implementation.
#include <iostream>
#include "workchain-proof-test-access.h"
#include <algorithm>

#include "block/workchain-confidential-native.h"
#include "block/workchain-registration-payment.h"
#include "block/workchain-registration-proof.h"
#include "block/workchain-registration-settlement.h"
#include "block/workchain-registration.h"
#include "td/utils/misc.h"
#include "td/utils/tests.h"
#include "vm/vm.h"
#include "workchain-possession-test-policy.h"
#include "block/workchain-possession-replay.h"

TEST(RegistrationDeletionProbe, SameIntentOldProof) {
  // v2 wallet vector, test-only s=71, k=997; canonical host context below.
  auto fill = [](unsigned char byte) {
    td::Bits256 value;
    std::fill(value.as_slice().begin(), value.as_slice().end(), byte);
    return value;
  };
  block::WorkchainConfidentialAccount a{};
  a.global_id = -23903;
  a.genesis_hash = fill(1);
  a.address = {2, fill(2), fill(3)};
  a.bindings = {fill(4), fill(5), fill(6)};
  a.schema_version = 1;
  a.relation_profile = 1;
  a.proof_profile = 2;
  a.key_epoch = 0;
  auto key = td::hex_decode("da6b841f2b72c6d5e15bd974905e1e218b1aa5c4eb4da5ea34bfeebab76dbf25");
  ASSERT_TRUE(key.is_ok());
  a.public_key.as_slice().copy_from(key.ok());
  auto possession = block::test::possession_policy(a);
  auto encoded = td::hex_decode(
      "b4262c4f436f97163b68860a20fda0f8b34b8baa176bb5e1f44a5c85b1785c6f"
      "c7bb758bd0142af29299619ba90b5f34cbab256874baf03e4c4ab8feec7d340b");
  ASSERT_TRUE(encoded.is_ok());
  std::array<unsigned char, 64> proof;
  std::copy(encoded.ok().begin(), encoded.ok().end(), proof.begin());
  auto meter = block::WorkchainProofTestAccess::create(433);
  auto result = block::verify_workchain_registration_possession(a, possession, proof, meter);
  ASSERT_EQ(meter.consumed(), 433u);
  auto short_meter = block::WorkchainProofTestAccess::create(432);
  auto short_result = block::verify_workchain_registration_possession(a, possession, proof, short_meter);
  ASSERT_TRUE(short_result.is_error());
  ASSERT_EQ(short_result.code(), -7201);
  ASSERT_EQ(short_result.message(), "engine underestimated attempted verification work");
  ASSERT_EQ(short_meter.consumed(), 0u);
#if !defined(TOS_CONFIDENTIAL_PROOF_BACKEND_LINKED)
#error This experiment requires the real linked kernel
#endif
  ASSERT_TRUE(result.is_ok());
  ASSERT_TRUE(block::verify_workchain_registration_possession(a, possession, proof, meter).is_error());
  ASSERT_EQ(meter.consumed(), 433u);
  auto invalid_proof = proof;
  invalid_proof[0] ^= 1;
  auto failed_meter = block::WorkchainProofTestAccess::create(866);
  auto invalid_result = block::verify_workchain_registration_possession(a, possession, invalid_proof, failed_meter);
  ASSERT_TRUE(invalid_result.is_error());
  ASSERT_EQ(invalid_result.code(), -7200);
  ASSERT_EQ(failed_meter.consumed(), 433u);
  auto sticky_result = block::verify_workchain_registration_possession(a, possession, proof, failed_meter);
  ASSERT_TRUE(sticky_result.is_error());
  ASSERT_EQ(sticky_result.code(), -7200);
  ASSERT_EQ(failed_meter.consumed(), 433u);
  a.funding = {10, 0, fill(8)};
  a.available = {fill(0), fill(0)};
  a.auth_nonce = 0;
  a.available_revision = 0;
  a.lifecycle = block::WorkchainAccountActive{};
  block::WorkchainRegistrationPolicy policy{a.global_id, a.genesis_hash, fill(7), a.bindings, 1, 1, 2, 10, possession};
  a.address.instance = block::derive_workchain_registration_operation_id(policy,a).move_as_ok();
  ASSERT_EQ(a.address.instance.to_hex(), "0DB963E03494EF62B42EBF2CDB9A69F109DAE126399C80801DDACF8E98660A12");
  ASSERT_TRUE(a.address.instance != policy.workchain_instance);
  // Fresh wallet proof for the registration-operation incarnation (test s=71,
  // k=997), generated by uno/prover/examples/m3-scenario.rs, not a host signer.
  encoded = td::hex_decode("b4262c4f436f97163b68860a20fda0f8b34b8baa176bb5e1f44a5c85b1785c6f"
                           "873d971f326453994891ad01efa497ce948bac814421931e7f24e5e091ad4c0f");
  ASSERT_TRUE(encoded.is_ok());
  std::copy(encoded.ok().begin(), encoded.ok().end(), proof.begin());
  auto cell = block::encode_workchain_confidential_account(a);
  ASSERT_TRUE(cell.is_ok());
  block::WorkchainRegistrationSnapshot old{{2, {1, 1000000, 0, 0}, 0}, {}, 0, fill(8), 100};
  auto aliased = a;
  aliased.address.instance = policy.workchain_instance;
  auto alias_cell = block::encode_workchain_confidential_account(aliased).move_as_ok();
  auto rejected_alias = block::WorkchainProofTestAccess::with_budget(100000, [&](auto& verification_budget) { return block::execute_workchain_registration(policy, old, a.address.account, alias_cell, proof, verification_budget); });
  ASSERT_TRUE(rejected_alias.is_error());
  ASSERT_EQ(rejected_alias.error().code(), -7200);
  ASSERT_EQ(rejected_alias.error().message(), "registration incarnation differs from operationID");
  block::WorkchainRegistrationReplayInput replay{a.address.instance,
      block::rebuild_workchain_possession_context(possession,a),proof};
  auto replay_root=block::encode_workchain_replay_input(replay).move_as_ok();
  ASSERT_EQ(vm::std_boc_serialize(replay_root,0).move_as_ok().size(),557u);
  auto registered = block::WorkchainProofTestAccess::with_budget(100000, [&](auto& verification_budget) { return block::replay_workchain_registration(policy, old, a.address.account, cell.ok(), replay_root, verification_budget); });
  ASSERT_TRUE(registered.is_ok());
  ASSERT_EQ(registered.ok().payer_balance, 90u);
  // Hypothetical authenticated post-close + deleted snapshot; this experiment
  // does not implement deletion or pretend to exercise Native message replay.
  // The payer supplies another deposit. The historical count remains one.
  auto after_close = old;
  after_close.coordinator = block::decode_workchain_coordinator_state(registered.ok().coordinator_data).move_as_ok();
  after_close.coordinator.refundable_deposits = 0;
  after_close.payer_balance = registered.ok().payer_balance;
  auto closed = block::decode_workchain_confidential_account(registered.ok().account_data).move_as_ok();
  closed.lifecycle = block::WorkchainAccountClosed{};
  closed.auth_nonce = 1;
  auto closed_cell = block::encode_workchain_confidential_account(closed).move_as_ok();
  after_close.existing_account = closed_cell;
  auto retained_meter = block::WorkchainProofTestAccess::create(433);
  auto retained = block::replay_workchain_registration(policy, after_close, a.address.account,
      cell.ok(), replay_root, retained_meter);
  ASSERT_TRUE(retained.is_error());
  ASSERT_EQ(retained.error().code(), -7200);
  ASSERT_EQ(retained.error().message(), "confidential account already exists");
  ASSERT_EQ(retained_meter.consumed(), 0u);
  // Verified absence is precisely the hypothetical deletion premise. Acquisition
  // failure must never be represented by this null value in a real host.
  after_close.existing_account.clear();
  auto same_id = block::derive_workchain_registration_operation_id(policy, a).move_as_ok();
  ASSERT_EQ(same_id, a.address.instance);
  auto second_meter = block::WorkchainProofTestAccess::create(433);
  auto second = block::replay_workchain_registration(policy, after_close, a.address.account,
      cell.ok(), replay_root, second_meter);
  ASSERT_TRUE(second.is_ok());
  ASSERT_EQ(second_meter.consumed(), 433u);
  ASSERT_EQ(second.ok().payer_balance, 80u);
  auto again = block::decode_workchain_coordinator_state(second.ok().coordinator_data).move_as_ok();
  ASSERT_EQ(again.system.registered_accounts, 2u);
  ASSERT_EQ(again.refundable_deposits, 10u);
  std::cout << "REGISTRATION_OLD_PROOF_ACCEPTED status=OK units=433 count=2 bucket=10 payer=80 incarnation="
            << same_id.to_hex() << "\n";
  std::cout << "RETAINED_RECORD status=-7200 reason=confidential account already exists units=0\n";
}
